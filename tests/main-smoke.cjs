const { app, BrowserWindow, safeStorage } = require('electron')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const assert = require('node:assert/strict')
if (process.platform === 'linux') app.disableHardwareAcceleration()
const root = fs.mkdtempSync(path.join(process.env.TMPDIR || os.tmpdir(), 'ciq-main-smoke-'))
process.env.CIQ_TEST_USER_DATA = path.join(root, 'user')
process.env.CIQ_TEST_IMPORT_HOME = path.join(root, 'import-home')
const project = path.join(root, 'fixture-project')
fs.mkdirSync(project)
fs.mkdirSync(process.env.CIQ_TEST_IMPORT_HOME)
fs.writeFileSync(path.join(process.env.CIQ_TEST_IMPORT_HOME, '.claude.json'), JSON.stringify({ projects: { [project]: {} } }))
const importDbPath = path.join(process.env.CIQ_TEST_IMPORT_HOME, '.local', 'share', 'opencode')
fs.mkdirSync(importDbPath, { recursive: true })
const { DatabaseSync } = require('node:sqlite')
const importDb = new DatabaseSync(path.join(importDbPath, 'opencode.db'))
importDb.exec('CREATE TABLE project (worktree TEXT)')
importDb.prepare('INSERT INTO project VALUES (?)').run(project)
importDb.close()
require(process.env.CIQ_PACKAGE_APP_ROOT ? path.join(process.env.CIQ_PACKAGE_APP_ROOT, 'electron', 'main.cjs') : '../electron/main.cjs')
const until = async condition => {
  for (let n = 0; n < 150; n++) {
    const value = await condition()
    if (value) return value
    await new Promise(resolve => setTimeout(resolve, 50))
  }
  throw new Error('Timed out waiting for desktop app readiness')
}
app.whenReady().then(async () => {
  const window = await until(() => BrowserWindow.getAllWindows()[0])
  await until(() => !window.webContents.isLoading() && window.webContents.getURL().endsWith('index.html'))
  await until(() => window.webContents.executeJavaScript('Boolean(window.ciq && document.querySelector("h1"))'))
  const state = await window.webContents.executeJavaScript('window.ciq.invoke("state")')
  assert.equal(state.connected, false)
  assert.equal(state.projects.length, 0)
  assert.ok(!('key' in state))
  assert.equal(state.freeEnabled, true)
  assert.equal(state.freeProvider, 'opencode')
  assert.equal(state.updates.autoDownload, true)
  const info = await window.webContents.executeJavaScript('window.ciq.invoke("engine.info")')
  assert.equal(info.version, '2.2.6')
  await assert.rejects(window.webContents.executeJavaScript('window.ciq.invoke("unsupported")'), /Unsupported action/)
  const freeModels = await until(async () => {
    const current = await window.webContents.executeJavaScript('window.ciq.invoke("state")')
    return current.models.length > 0 ? current.models : false
  })
  assert.ok(freeModels.some(model => model.providerID === 'opencode'))
  const providers = await window.webContents.executeJavaScript('window.ciq.invoke("provider.list")')
  assert.ok(providers.data.some(provider => provider.id === 'anthropic'))
  assert.ok(providers.data.every(provider => Array.isArray(provider.env) && provider.env.length > 0))
  const security = await window.webContents.executeJavaScript('({ require:typeof require, process:typeof process, preview:document.querySelector(".preview-label")?.textContent, modal:document.querySelector("dialog[open] h2")?.textContent })')
  assert.equal(security.require, 'undefined')
  assert.equal(security.process, 'undefined')
  assert.equal(security.preview, undefined)
  assert.equal(security.modal, undefined)
  const health = await window.webContents.executeJavaScript('window.ciq.invoke("diagnostics")')
  assert.equal(health.engine.status, 'ready')
  assert.equal(health.rendererSandbox, true)
  assert.equal(health.platform, process.platform)
  const discovered = await window.webContents.executeJavaScript('window.ciq.invoke("project.discover")')
  assert.equal(discovered.candidates.length, 1)
  assert.deepEqual(discovered.warnings, [])
  assert.deepEqual(discovered.candidates[0].sources, ['Claude', 'OpenCode'])
  const imported = await window.webContents.executeJavaScript(`window.ciq.invoke('project.import', { ids: [${JSON.stringify(discovered.candidates[0].id)}] })`)
  assert.equal(imported.imported, 1)
  assert.equal(imported.state.projects.length, 1)
  const { Store } = require(process.env.CIQ_PACKAGE_APP_ROOT ? path.join(process.env.CIQ_PACKAGE_APP_ROOT, 'electron', 'core.cjs') : '../electron/core.cjs')
  const vault = await new Store(process.env.CIQ_TEST_USER_DATA, safeStorage).load()
  if (vault.canEncrypt()) {
    await vault.setProviderKey('groq', 'ciq-smoke-fixture-not-a-real-key', true)
    const restored = await new Store(process.env.CIQ_TEST_USER_DATA, safeStorage).load()
    assert.equal(await restored.getProviderKey('groq'), 'ciq-smoke-fixture-not-a-real-key')
    assert.equal(fs.readFileSync(vault.providerVault).includes(Buffer.from('ciq-smoke-fixture-not-a-real-key')), false)
    await restored.clearProviderKey('groq')
  }
  await window.webContents.executeJavaScript(`document.querySelector('.import-projects-button').click()`)
  await until(() => window.webContents.executeJavaScript(`document.querySelector('dialog h2')?.textContent === 'Import your projects'`))
  await window.webContents.executeJavaScript(`Array.from(document.querySelectorAll('dialog button')).find(b => b.textContent.includes('Find projects')).click()`)
  await until(() => window.webContents.executeJavaScript(`Boolean(document.querySelector('.import-row'))`))
  assert.equal(await window.webContents.executeJavaScript(`document.querySelector('.import-row').textContent.includes('Already open')`), true)
  fs.mkdirSync(path.join(__dirname, '..', 'test-results'), { recursive: true })
  fs.writeFileSync(path.join(__dirname, '..', 'test-results', 'import-projects.png'), (await window.webContents.capturePage()).toPNG())
  await window.webContents.executeJavaScript(`document.querySelector('button[aria-label="Close dialog"]').click()`)
  fs.mkdirSync(path.join(__dirname, '..', 'test-results'), { recursive: true })
  await window.webContents.executeJavaScript('document.fonts.ready')
  fs.writeFileSync(path.join(__dirname, '..', 'test-results', 'native-onboarding.png'), (await window.webContents.capturePage()).toPNG())
  await window.webContents.executeJavaScript('window.ciq.invoke("engine.restart")')
  const restarted = await window.webContents.executeJavaScript('window.ciq.invoke("engine.info")')
  assert.notEqual(restarted.pid, info.pid)
  assert.throws(() => process.kill(info.pid, 0))
  const preserved = await window.webContents.executeJavaScript('window.ciq.invoke("state")')
  assert.equal(preserved.projects.length, 1)
  const enginePid = restarted.pid
  console.log(JSON.stringify({ success: true, nativeBridge: true, version: info.version, secureStorage: state.secureStorage, enginePid, security }, null, 2))
  app.once('will-quit', () => {
    assert.throws(() => process.kill(enginePid, 0), 'Owned engine must stop when the app quits')
    console.log('Owned coding engine cleanup verified.')
  })
  app.quit()
}).catch(error => { console.error(error); app.exit(1) })
